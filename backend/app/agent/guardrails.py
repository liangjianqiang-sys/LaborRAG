    @classmethod
    def check(cls, answer: str) -> str:
        """检查回答，必要时追加风险提示。"""
        extra_notes = []

        for rule in cls.CHECK_RULES:
            # 检查 trigger 是否出现在回答中
            if not re.search(rule["trigger"], answer):
                continue

            # 检查回答中是否已包含了必要的前提说明
            if re.search(rule["requires"], answer, re.IGNORECASE):
                continue

            # 未包含前提说明，记录需要追加的提示
            extra_notes.append(rule["hint"])

        if extra_notes:
            # 去重后追加
            unique_notes = list(dict.fromkeys(extra_notes))
            answer += "\n\n---\n**注意事项：**\n" + "\n".join(f"- {note}" for note in unique_notes)

        return answer
