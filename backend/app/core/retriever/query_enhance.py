def enhance_query(query: str) -> str:
    """增强查询：匹配口语关键词，补充法言法语和法条编号。

    返回增强后的查询字符串。如果无匹配，返回原查询。
    """
    enhancements = []
    for keyword, enhancement in _KEYWORD_MAP:
        if keyword in query:
            enhancements.append(enhancement)
            break  # 只取最长匹配，避免堆砌

    if enhancements:
        return f"{query} {' '.join(enhancements)}"
    return query
